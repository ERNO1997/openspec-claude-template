#!/usr/bin/env bash
# Exports a clean boilerplate (only what a new project needs) to a folder, so it can live in its own
# GitHub "Template repository". This repository stays the source of truth (install, audit, docs):
# edit files here and run this script again to refresh the boilerplate.
#
# It overwrites only the files it manages; everything else in the folder (including .git) is left alone.
#
# Usage: ./make-boilerplate.sh <path>
set -euo pipefail

TARGET="${1:-}"
if [ -z "$TARGET" ] || [ "$#" -gt 1 ]; then
  echo "Usage: ./make-boilerplate.sh <path>" >&2
  exit 1
fi

HERE="$(cd "$(dirname "$0")" && pwd)"
mkdir -p "$TARGET"
TARGET="$(cd "$TARGET" && pwd)"
[ "$TARGET" != "$HERE" ] || { echo "! The target must be a different folder." >&2; exit 1; }

# Keep in sync with the copy calls in install.sh, plus kickoff.md and .gitignore.
FILES=(
  openspec/config.yaml
  .claude/settings.json
  .claude/hooks/run-tests.sh
  .claude/agents/test-runner.md
  explore/_TEMPLATE/notes.md
  'bin/opsx:archive'
  'bin/opsx:archive-explore'
  kickoff.md
  .gitignore
)

for rel in "${FILES[@]}"; do
  mkdir -p "$TARGET/$(dirname "$rel")"
  cp -p "$HERE/$rel" "$TARGET/$rel"
  echo "+ $rel"
done
chmod +x "$TARGET/.claude/hooks/run-tests.sh" "$TARGET/bin/opsx:archive" "$TARGET/bin/opsx:archive-explore"

# README for projects created with "Use this template". The project will replace it with its own.
cat > "$TARGET/README.md" <<'EOF'
# New project (OpenSpec + Claude Code boilerplate)

Created from the boilerplate generated by
[openspec-claude-template](https://github.com/ERNO1997/openspec-claude-template).
Replace this README with your project's own once the kickoff is done.

## First steps

```bash
openspec init --tools claude        # adds the /opsx:* commands; keeps openspec/config.yaml
claude --model opus --effort medium
> Read kickoff.md and follow it.
```

The kickoff interviews you about the project, fills `context` in `openspec/config.yaml` and the test
command in `.claude/hooks/run-tests.sh`, writes `explore/kickoff/notes.md` with the first changes,
and then deletes itself. The first change (`project-skeleton`) goes through the normal flow:

| Phase | Command |
|---|---|
| Propose | `claude --model opus --effort medium`, then `/opsx:propose <name>` |
| Apply | `RUN_QA=1 claude --model sonnet --effort medium`, then `/opsx:apply <name>` (`/clear` every 3-5 tasks) |
| Archive | `bin/opsx:archive <name>` (no LLM) |

Workflow details and the quota rules are in the template repository's README and CHECKLIST.
EOF
echo "+ README.md"

echo
echo "Done: $TARGET"
if [ ! -d "$TARGET/.git" ]; then
  echo "To publish it as a GitHub template repository (not run by this script):"
  echo "  cd $TARGET && git init && git add -A && git commit -m 'OpenSpec + Claude Code boilerplate'"
  echo "  gh repo create <name> --private --source . --push"
  echo "  gh repo edit --template"
else
  echo "Review with 'git -C $TARGET status', then commit and push to refresh the template."
fi
